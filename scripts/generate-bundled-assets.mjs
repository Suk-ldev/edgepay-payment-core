import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../public/', import.meta.url));
const output = fileURLToPath(new URL('../src/bundled-assets.js', import.meta.url));
const checkOnly = process.argv.includes('--check');

const MIME_TYPES = Object.freeze({
  '.css': 'text/css; charset=utf-8',
  '.html': 'text/html; charset=utf-8',
  '.ico': 'image/x-icon',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.js': 'application/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.png': 'image/png',
  '.svg': 'image/svg+xml; charset=utf-8',
  '.webp': 'image/webp',
});

const TEXT_EXTENSIONS = new Set(['.css', '.html', '.js', '.json', '.svg']);

async function filesIn(directory) {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) result.push(...await filesIn(full));
    else if (entry.isFile()) result.push(full);
  }
  return result;
}

function jsString(value) {
  return JSON.stringify(value).replaceAll('\u2028', '\\u2028').replaceAll('\u2029', '\\u2029');
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&');
}

/**
 * 给 HTML 里引用的静态资源打上内容指纹。
 *
 * 资源是 public, max-age=3600，HTML 是 no-store。以前 dashboard.html 直接写
 * /app.js，升级完 HTML 立刻是新的、app.js 却还能在浏览器里旧一个小时——
 * 后台会出现"新功能死活不出现"，只能让人手动硬刷新。
 *
 * 指纹取自文件内容，所以内容不变就不会变，改一个字节就换一个 URL。
 * 资源查表用的是 pathname，查询串不参与，服务端不需要跟着改。
 */
function fingerprintHtmlReferences(html, assets) {
  let result = html;
  // 长路径先替换，避免短路径把长路径的前缀先吃掉。
  const ordered = [...assets.entries()].sort((left, right) => right[0].length - left[0].length);
  for (const [assetPath, hash] of ordered) {
    const pattern = new RegExp(`(["'])${escapeRegExp(assetPath)}(?:\\?[^"']*)?\\1`, 'gu');
    result = result.replaceAll(pattern, `$1${assetPath}?v=${hash.slice(0, 12)}$1`);
  }
  return result;
}

async function generate() {
  const rows = [];
  const sources = await filesIn(root);
  sources.sort((left, right) => left.localeCompare(right, 'en'));

  // 先把非 HTML 资源的内容指纹算出来，HTML 里的引用才有东西可写。
  const fingerprints = new Map();
  for (const full of sources) {
    const extension = path.extname(full).toLowerCase();
    if (extension === '.html') continue;
    const relative = `/${path.relative(root, full).replaceAll('\\', '/')}`;
    fingerprints.set(relative, createHash('sha256').update(await readFile(full)).digest('hex'));
  }

  for (const full of sources) {
    const relative = `/${path.relative(root, full).replaceAll('\\', '/')}`;
    const extension = path.extname(full).toLowerCase();
    let bytes = await readFile(full);
    if (extension === '.html') {
      bytes = Buffer.from(fingerprintHtmlReferences(bytes.toString('utf8'), fingerprints), 'utf8');
    }
    const type = MIME_TYPES[extension] ?? 'application/octet-stream';
    const hash = createHash('sha256').update(bytes).digest('hex');
    if (TEXT_EXTENSIONS.has(extension)) {
      rows.push(`  ${jsString(relative)}:{type:${jsString(type)},text:${jsString(bytes.toString('utf8'))},sha256:${jsString(hash)}}`);
    } else {
      rows.push(`  ${jsString(relative)}:{type:${jsString(type)},base64:${jsString(bytes.toString('base64'))},sha256:${jsString(hash)}}`);
    }
  }
  return `// Generated by scripts/generate-bundled-assets.mjs. Do not edit by hand.\n`
    + `const ASSETS=Object.freeze({\n${rows.join(',\n')}\n});\n`
    + `const binaryCache=new Map();\n`
    + `function binary(value){if(binaryCache.has(value))return binaryCache.get(value);const raw=atob(value);const bytes=Uint8Array.from(raw,c=>c.charCodeAt(0));binaryCache.set(value,bytes);return bytes}\n`
    + `export const BUNDLED_ASSET_PATHS=Object.freeze(Object.keys(ASSETS));\n`
    + `export async function fetchBundledAsset(request){const method=String(request.method||'GET').toUpperCase();if(!['GET','HEAD'].includes(method))return new Response('method_not_allowed',{status:405});const pathname=new URL(request.url).pathname;const asset=ASSETS[pathname];if(!asset)return new Response('not_found',{status:404,headers:{'cache-control':'no-store'}});const headers={'content-type':asset.type,'x-content-type-options':'nosniff','etag':'"'+asset.sha256+'"','cache-control':asset.type.startsWith('text/html')?'no-store':'public, max-age=3600'};return new Response(method==='HEAD'?null:(asset.text??binary(asset.base64)),{status:200,headers})}\n`;
}

const generated = await generate();
if (checkOnly) {
  const current = await readFile(output, 'utf8').catch(() => '');
  if (current !== generated) {
    console.error('src/bundled-assets.js 与 public/ 不一致；先运行 npm run assets:build');
    process.exit(1);
  }
} else {
  await writeFile(output, generated, 'utf8');
}
